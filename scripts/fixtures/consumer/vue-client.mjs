import assert from 'node:assert/strict';
import { installDom } from './assert-svg.mjs';
installDom();
const { createApp, h, ref, nextTick } = await import('vue');
const { Mosque } = await import('@muslim-icons/vue');
const size = ref(24);
const icon = ref();
let clicks = 0;
const app = createApp({ render: () => h(Mosque, { size: size.value, ref: icon, onClick: () => clicks++, 'aria-label': 'Mosque' }) });
app.mount('#app');
assert.equal(icon.value.$el.tagName, 'svg');
icon.value.$el.dispatchEvent(new MouseEvent('click', { bubbles: true }));
assert.equal(clicks, 1);
size.value = 48;
await nextTick();
assert.equal(icon.value.$el.getAttribute('width'), '48');
assert.equal(icon.value.$el.getAttribute('aria-hidden'), null);
app.unmount();
console.log('Vue: reactive props, native SVG attributes and click events passed');
